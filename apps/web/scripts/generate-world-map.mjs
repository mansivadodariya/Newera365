// Generates packages/ui/src/components/worldMapData.ts: the world land
// silhouette as a single SVG path (Natural Earth projection, Antarctica
// dropped) plus the projected coordinates of the focus-market anchors.
//
// Input: scripts/data/countries-110m.json (world-atlas@2 topojson).
// Rerun after changing MARKETS or the projection:
//   node apps/web/scripts/generate-world-map.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoMercator, geoPath } from 'd3-geo';
import { merge } from 'topojson-client';

const __dirname = dirname(fileURLToPath(import.meta.url));

const WIDTH = 1000;
const ANTARCTICA_ID = '010';

// Market anchors: [lng, lat] of each market's financial capital.
const MARKETS = {
  india: [72.88, 19.08], // Mumbai
  mena: [55.27, 25.2], // Dubai
  indonesia: [106.85, -6.2], // Jakarta
  vietnam: [106.7, 10.78], // Ho Chi Minh City
};

// ISO 3166-1 numeric ids per focus region (world-atlas countries-110m).
// MENA: GCC + Egypt, Jordan, Morocco (Bahrain has no 110m geometry).
const REGION_COUNTRIES = {
  india: ['356'],
  mena: ['682', '784', '634', '414', '512', '818', '400', '504'],
  indonesia: ['360'],
  vietnam: ['704'],
};

const topo = JSON.parse(readFileSync(join(__dirname, 'data', 'countries-110m.json'), 'utf8'));
const landNoAntarctica = merge(
  topo,
  topo.objects.countries.geometries.filter((g) => g.id !== ANTARCTICA_ID),
);

const projection = geoMercator();
projection.fitWidth(WIDTH, landNoAntarctica);
const [[x0, y0], [x1, y1]] = geoPath(projection).bounds(landNoAntarctica);
const height = Math.ceil(y1 - y0);
projection.fitExtent(
  [
    [0, 0],
    [WIDTH, height],
  ],
  landNoAntarctica,
);

const path = geoPath(projection).digits(1);
const d = path(landNoAntarctica);

const regionPaths = Object.fromEntries(
  Object.entries(REGION_COUNTRIES).map(([id, ids]) => [
    id,
    path(merge(topo, topo.objects.countries.geometries.filter((g) => ids.includes(g.id)))),
  ]),
);

const points = Object.fromEntries(
  Object.entries(MARKETS).map(([id, lngLat]) => {
    const [x, y] = projection(lngLat);
    return [id, { x: +x.toFixed(1), y: +y.toFixed(1) }];
  }),
);

const out = `// Generated by apps/web/scripts/generate-world-map.mjs. Do not edit by hand.
// World land silhouette (Natural Earth projection, Antarctica dropped) from
// world-atlas countries-110m, plus projected focus-market anchor coordinates.

export const WORLD_MAP_WIDTH = ${WIDTH};
export const WORLD_MAP_HEIGHT = ${height};

export const MARKET_POINTS = ${JSON.stringify(points, null, 2)} as const;

export const REGION_PATHS: Record<keyof typeof MARKET_POINTS, string> = {
${Object.entries(regionPaths)
  .map(([id, p]) => `  ${id}:\n    '${p}',`)
  .join('\n')}
};

export const WORLD_LAND_PATH =
  '${d}';
`;

const outPath = join(__dirname, '..', '..', '..', 'packages', 'ui', 'src', 'components', 'worldMapData.ts');
writeFileSync(outPath, out);
console.log(`wrote ${outPath}: viewBox 0 0 ${WIDTH} ${height}, path ${d.length} chars`);
console.log('points:', JSON.stringify(points));
